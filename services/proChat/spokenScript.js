function spellUrdu(word) {
  const w = word.replace(/[\u0640\u064E\u0654]/g, '');
  const last = w.length - 1;
  let out = '';
  let afterConsonant = false;
  let lastConsonant = '';
  for (let i = 0; i <= last; i += 1) {
    const ch = w[i];
    const next = w[i + 1];
    if (CONSONANTS[ch]) {
      if (next === 'ھ' && ASPIRATED[ch]) {
        out += ASPIRATED[ch];
        lastConsonant = ASPIRATED[ch];
        i += 1;
      } else if (ch === 'ن' && i > 0 && i < last && CONSONANTS[next] && next !== 'ن') {
        // Noon before another consonant after a vowel: a nasal (پنجاب).
        out += 'ं';
        continue;
      } else {
        out += CONSONANTS[ch];
        lastConsonant = CONSONANTS[ch];
      }
      afterConsonant = true;
      continue;
    }
    switch (ch) {
      case 'ھ':
        out += 'ह';
        afterConsonant = true;
        break;
      case 'ہ':
      case 'ۃ':
      case 'ة':
        if (i === last && i > 0 && afterConsonant) {
          out += 'ा';
          afterConsonant = false;
        } else {
          out += 'ह';
          lastConsonant = 'ह';
          afterConsonant = true;
        }
        break;
      case 'ا':
      case 'ٱ':
        if (i === 0) {
          if (next === 'و') {
            out += 'ओ';
            i += 1;
          } else if (next === 'ی' || next === 'ي') {
            out += 'ए';
            i += 1;
          } else {
            out += 'अ';
          }
        } else {
          out += afterConsonant ? 'ा' : 'आ';
        }
        afterConsonant = false;
        break;
      case 'آ':
        out += i > 0 && afterConsonant ? 'ा' : 'आ';
        afterConsonant = false;
        break;
      case 'و':
        if (i === 0 || (afterConsonant && (VOWEL_LETTERS.has(next) || next === 'ّ'))) {
          out += 'व';
          lastConsonant = 'व';
          afterConsonant = true;
        } else {
          out += afterConsonant ? 'ो' : 'ओ';
          afterConsonant = false;
        }
        break;
      case 'ی':
      case 'ي':
      case 'ى':
        if (i === 0) {
          out += 'य';
          lastConsonant = 'य';
          afterConsonant = true;
        } else if (afterConsonant) {
          if (next === 'ا' || next === 'و') {
            out += 'िय';
            lastConsonant = 'य';
            afterConsonant = true;
          } else if (next === 'ں' && i + 1 === last) {
            out += 'ें';
            i += 1;
            afterConsonant = false;
          } else {
            out += 'ी';
            afterConsonant = false;
          }
        } else if (next && VOWEL_LETTERS.has(next)) {
          out += 'य';
          lastConsonant = 'य';
          afterConsonant = true;
        } else {
          out += 'ई';
          afterConsonant = false;
        }
        break;
      case 'ے':
      case 'ۓ':
        out += afterConsonant ? 'े' : 'ए';
        afterConsonant = false;
        break;
      case 'ئ':
        if (next === 'ی' || next === 'ي') {
          out += 'ई';
          i += 1;
        } else if (next === 'ے') {
          out += 'ए';
          i += 1;
        } else if (next === 'و') {
          out += 'ओ';
          i += 1;
        } else {
          out += 'इ';
        }
        afterConsonant = false;
        break;
      case 'ؤ':
        out += 'ओ';
        afterConsonant = false;
        break;
      case 'ء':
        break;
      case 'ع':
        if (i === 0) {
          if (next === 'ا') i += 1;
          out += next === 'ا' ? 'आ' : 'अ';
        } else if (afterConsonant) {
          out += 'ा';
        }
        afterConsonant = false;
        break;
      case 'ں':
        out += 'ं';
        afterConsonant = false;
        break;
      case 'ِ':
        if (afterConsonant) out += 'ि';
        afterConsonant = false;
        break;
      case 'ُ':
        if (afterConsonant) out += 'ु';
        afterConsonant = false;
        break;
      case 'ّ':
        if (afterConsonant && lastConsonant) out += `्${lastConsonant}`;
        break;
      case 'ْ':
        if (afterConsonant) out += '्';
        break;
      case 'ً':
        out += 'न';
        break;
      case 'ٰ':
        out += 'ा';
        afterConsonant = false;
        break;
      default:
        if (ch >= '\u064B' && ch <= '\u065F') break;
        out += ch;
        afterConsonant = false;
    }
  }
  return out;
}

function urduToDevanagari(line, guessed) {
  const words = [...line.matchAll(URDU_WORD)];
  let out = '';
  let at = 0;
  words.forEach((match, k) => {
    const word = match[0];
    const before = line.slice(at, match.index);
    out += before;
    at = match.index + word.length;
    const neighbours = [words[k - 1]?.[0], words[k + 1]?.[0]];
    const nearMoney = neighbours.some((w) => MONEY_WORDS.has(w) || URDU_NUMBERS.includes(w));
    if (word === 'میں') {
      const prev = words[k - 1]?.[0];
      // "I" at the start of a line or clause, or after a word like مگر / تو;
      // "in" after a place, plan or time word or an English word.
      const latinBefore = /[A-Za-z0-9]\s*$/.test(before);
      const afterWord = k > 0 && /^\s*$/.test(before) && IN_AFTER.has(prev);
      const clauseStart = k === 0 || /[۔؟!?.،,:;]\s*$/.test(before) || (/^\s*$/.test(before) && I_AFTER.has(prev));
      out += clauseStart && !latinBefore && !afterWord ? 'मैं' : 'में';
    } else if (NOT_NUMBER[word] && !nearMoney) out += NOT_NUMBER[word];
    else if (WORDS[word]) out += WORDS[word];
    else {
      guessed?.add(word);
      out += spellUrdu(word);
    }
  });
  out += line.slice(at);
  return out
    .replace(/[\u06F0-\u06F9]/g, (d) => String(d.charCodeAt(0) - 0x06F0))
    .replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۔؟،؛٪]/g, (p) => PUNCTUATION[p]);
}

function gurmukhiToDevanagari(line) {
  let out = '';
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    const code = ch.charCodeAt(0);
    if (code < 0x0A00 || code > 0x0A7F) {
      out += ch;
      continue;
    }
    if (code >= 0x0A66 && code <= 0x0A6F) out += String(code - 0x0A66);
    else if (ch === 'ੰ') out += 'ं';
    else if (ch === 'ੱ') {
      // Addak doubles the next consonant.
      const next = line.charCodeAt(i + 1);
      if (next >= 0x0A15 && next <= 0x0A5E) out += `${String.fromCharCode(next - 0x100)}्`;
    } else if (ch === 'ੲ') out += 'इ';
    else if (ch === 'ੳ') out += 'उ';
    else if (ch === 'ੴ') out += 'एक ओंकार';
    else if (ch === 'ੵ') out += '्य';
    else if (ch === 'ੑ') out += '';
    else if (ch === 'ਲ਼') out += 'ल';
    else out += String.fromCharCode(code - 0x100);
  }
  return out;
}

// The line as the Hindi voice should read it. Text with no Urdu or
// Gurmukhi letters comes back unchanged. Urdu words missing from WORDS
// (spelled letter by letter, often wrongly) are added to `guessed`.
export function toSpokenDevanagari(line, guessed = null) {
  let out = String(line ?? '');
  if (URDU_SCRIPT.test(out)) out = urduToDevanagari(out, guessed);
  if (GURMUKHI.test(out)) out = gurmukhiToDevanagari(out);
  return out;
}

// Rewrites a stream of reply text for the voice. Text is held back to the
// last space or punctuation so a word split across chunks is spelled whole.
export function spokenScriptStream(input, onChange = null) {
  let pending = '';
  let original = '';
  let spoken = '';
  const guessed = new Set();
  const send = (controller, part) => {
    const said = toSpokenDevanagari(part, guessed);
    original += part;
    spoken += said;
    controller.enqueue(said);
  };
  const reader = input.getReader();
  return new ReadableStream({
    async pull(controller) {
      for (;;) {
        const { done, value } = await reader.read();
        if (done) {
          if (pending) send(controller, pending);
          pending = '';
          // One line per reply (RAVI_DEBUG), when anything was rewritten.
          if (spoken !== original) onChange?.(original.trim(), spoken.trim(), [...guessed]);
          controller.close();
          return;
        }
        pending += String(value ?? '');
        const cut = Math.max(pending.lastIndexOf(' '), pending.lastIndexOf('\n'), pending.search(/[۔؟،.!?,][^۔؟،.!?,]*$/));
        if (cut < 0) continue;
        const ready = pending.slice(0, cut + 1);
        pending = pending.slice(cut + 1);
        send(controller, ready);
        return;
      }
    },
    cancel(reason) {
      return reader.cancel(reason);
    },
  });
}
